import type { TranslateProjectDraft } from "@/lib/data/client";
import type { LanguageCode, TranslationQuality } from "@/lib/types";
import { config } from "@/lib/config";
import { isDefaultCaptionStyle, type CaptionStyleChoice } from "@/lib/captionOptions";
import type { PresenterTranslate } from "@/lib/presenterTranslate";
import type { StagedUpload } from "@/lib/data/uploads";

/**
 * Pure helpers behind the "Translate a video" form: validation and the exact object that goes
 * to createTranslateProject. See adDraft.ts for why they live outside the component.
 */

export type TranslateFormErrors = Partial<Record<"video" | "projectName" | "targets" | "rights" | "form", string>>;

export type TranslateFormState = {
  /** The picked file; after a refresh only the staged copy in storage is left (2 Nov 2026), with the file's name and length. */
  video?: { file?: File; seconds?: number; staged?: StagedUpload };
  /** A stored video as the source (no upload): a finished ad ("Localize this ad", rights recorded as generated here) or an earlier translation's own upload ("Add a language", 31 Oct 2026). */
  sourceAd?: { id: string; seconds: number };
  /** Whether the rights box must be ticked; default: only for an upload. "Add a language" asks again for the reused upload. */
  rightsRequired?: boolean;
  projectName: string;
  source: LanguageCode | "auto";
  targets: LanguageCode[];
  quality: TranslationQuality;
  rights: boolean;
  keepTerms: string;
  format: "original" | "9:16";
  enhance: boolean;
  trimSilence: boolean;
  captionPosition: "low" | "middle";
  /** Caption choices (26 Oct 2026); sent only when they differ from the original look. */
  captionStyle?: CaptionStyleChoice;
  removeMusic?: boolean;
  cleanVoice?: boolean;
  removeText?: boolean;
  /** Rows of "in the video" → "say instead"; empty rows are left out. */
  replaceTerms?: { from: string; to: string }[];
  instructions?: string;
  speaker?: "original" | "presenter";
  presenter?: PresenterTranslate;
};

/** The new options as draft keys, only when chosen, so a draft with the defaults is exactly as before. */
function extras(s: TranslateFormState) {
  return {
    ...(s.captionStyle && !isDefaultCaptionStyle(s.captionStyle) ? { captionStyle: s.captionStyle } : {}),
    ...(s.removeMusic ? { removeMusic: true } : {}),
    ...(s.cleanVoice ? { cleanVoice: true } : {}),
    ...(s.removeText ? { removeText: true } : {}),
    ...(cleanReplace(s.replaceTerms).length ? { replaceTerms: cleanReplace(s.replaceTerms) } : {}),
    ...(s.instructions?.trim() ? { instructions: s.instructions.trim().slice(0, 300) } : {}),
    ...(s.speaker === "presenter" && s.presenter ? { speaker: "presenter" as const, presenter: s.presenter } : {}),
  };
}

export function validateTranslateForm(s: TranslateFormState): TranslateFormErrors {
  const next: TranslateFormErrors = {};
  const tooLong = s.video?.seconds !== undefined && s.video.seconds > config.limits.translateVideoMaxSeconds;
  if (!s.video && !s.sourceAd) next.video = "Add the video you want to translate.";
  else if (tooLong) next.video = `Videos up to ${config.limits.translateVideoMaxSeconds / 60} minutes for now.`;
  if (s.projectName.trim().length < 2) next.projectName = "Give the project a name so you can find it later.";
  if (s.targets.length === 0) next.targets = "Choose at least one target language.";
  if (!s.rights && (s.rightsRequired ?? !s.sourceAd)) next.rights = "We can only translate videos you own, with the speaker's consent. Tick the box to continue.";
  return next;
}

/** Filled rows only, trimmed, at most 10. */
export function cleanReplace(rows: { from: string; to: string }[] | undefined) {
  return (rows ?? []).map((r) => ({ from: r.from.trim(), to: r.to.trim() })).filter((r) => r.from && r.to).slice(0, 10);
}

/** Comma- or newline-separated terms, trimmed, at most 20. */
export function parseKeepTerms(raw: string) {
  return raw.split(/[,\n]/).map((t) => t.trim()).filter(Boolean).slice(0, 20);
}

/** Exactly what the form sends to createTranslateProject. Requires a video, or a finished ad as the source (validated before). */
export function buildTranslateDraft(s: TranslateFormState & ({ video: { file?: File; seconds?: number; staged?: StagedUpload } } | { sourceAd: { id: string; seconds: number } })): TranslateProjectDraft {
  if (s.sourceAd) {
    return {
      name: s.projectName.trim(),
      sourceProjectId: s.sourceAd.id,
      sourceSeconds: Math.round(s.sourceAd.seconds),
      sourceLanguage: s.source,
      targetLanguages: s.targets,
      quality: s.quality,
      keepTerms: parseKeepTerms(s.keepTerms),
      format: s.format,
      enhance: s.enhance,
      trimSilence: s.trimSilence,
      captionPosition: s.captionPosition,
      ...extras(s),
      // Generated by the customer in the app: the rights are established without a checkbox and stored with the project.
      rightsConfirmed: true,
    };
  }
  const video = s.video!;
  return {
    name: s.projectName.trim(),
    // The file when it is still in memory; the staged copy (only as a key when there is one) lets a restored draft start without it.
    video: video.file,
    ...(video.staged ? { staged: video.staged } : {}),
    sourceSeconds: Math.round(video.seconds ?? video.staged?.seconds ?? 30),
    sourceLanguage: s.source,
    targetLanguages: s.targets,
    quality: s.quality,
    keepTerms: parseKeepTerms(s.keepTerms),
    format: s.format,
    enhance: s.enhance,
    trimSilence: s.trimSilence,
    captionPosition: s.captionPosition,
    ...extras(s),
    rightsConfirmed: s.rights,
  };
}
