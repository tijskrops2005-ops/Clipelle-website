-- Default deny for the Data API roles (anon = publishable key without a session, authenticated =
-- publishable key with a signed-in user) on EVERY table in public, now and for tables added later.
-- The app reaches Postgres as `postgres` over the pooler and Storage with the secret key, neither of
-- which is affected. Re-runnable: everything here is idempotent. Verified by src/lib/db/security.test.ts.
DO $$
DECLARE t record;
BEGIN
  FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t.tablename);
  END LOOP;
END $$;
